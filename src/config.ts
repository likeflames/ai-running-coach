/* 服务器地址配置
 *
 * 支持多个候选地址：App 启动后会自动尝试，连不上的自动跳到下一个，
 * 并记住最后成功的那个（下次启动优先使用）。
 *
 * 为什么 IP 排第一，而不是 HTTPS 域名
 * ---------------------------------
 * 域名和证书都配好了（Let's Encrypt，Caddy 自动续期），刚开通那半小时确实能用。
 * 但之后从大陆网络发起 TLS 握手会被稳定重置（10 次 10 次 RST，换 SNI 也一样），
 * 而同一条链路走 80 端口完全正常 —— 这是未备案域名在 443 上被拦的典型表现。
 * 所以不能让 HTTPS 排在前面：那会让每次启动先撞一次墙。
 *
 * 想真正用上 HTTPS，只有两条路：把域名备案，或者把服务放到境外服务器。
 * 在那之前，HTTPS 留着当第二候选，哪天通了会自动被选中。
 */
